/**
 * Builds the browser extension into dist-extension/ and lifekit-extension.zip.
 * Generates the tool list from src/config/tools.ts and the website address from
 * VITE_SITE_URL (environment or .env files), so the extension always matches the site.
 *
 *   VITE_SITE_URL=https://your-domain.com npm run build:extension
 */
import { cpSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { zipSync } from 'fflate';
import { readdirSync, statSync } from 'node:fs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const src = join(root, 'extension');
const out = join(root, 'dist-extension');

function readEnvFile(name) {
  const p = join(root, name);
  if (!existsSync(p)) return {};
  return Object.fromEntries(
    readFileSync(p, 'utf8').split(/\r?\n/).map((l) => l.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/)).filter(Boolean)
      .map((m) => [m[1], m[2].replace(/^['"]|['"]$/g, '')]),
  );
}
const env = { ...readEnvFile('.env'), ...readEnvFile('.env.production'), ...process.env };
const site = (env.VITE_SITE_URL || '').replace(/\/+$/, '');
if (!/^(https:\/\/[^/]+|http:\/\/localhost(:\d+)?)$/.test(site)) {
  console.error('✗ Set VITE_SITE_URL to your live https:// address (no path), e.g. VITE_SITE_URL=https://example.com');
  process.exit(1);
}

